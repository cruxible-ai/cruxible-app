'use client';

import * as React from 'react';
import { cn } from '@/lib/utils';
import { ReportHeader } from './report-header';
import { ExecutiveSummary } from './executive-summary';
import { NetworkEffectsDetail } from './network-effects-detail';
import { MethodologySection } from './methodology-section';
import type { NetworkReportData } from '@/lib/report-types';

interface NetworkReportProps {
  data: NetworkReportData;
  showPrintStyles?: boolean;
  className?: string;
}

/**
 * NetworkReport - Main report component that composes all sections.
 *
 * This component renders the "Network Impact Report" showing the "aha moment":
 * Gross Lift → Net Margin Impact after accounting for cannibalization and halo effects.
 *
 * Sections:
 * 1. ReportHeader - Logo, retailer name, promo details
 * 2. ExecutiveSummary - KPI cards, waterfall chart, recommendations
 * 3. NetworkEffectsDetail - Product graph, cannibalization/halo tables
 * 4. MethodologySection - Data quality, limitations, improvements
 *
 * Features:
 * - Print-optimized with page breaks between sections
 * - Responsive design for screen and print
 * - Uses existing Cruxible UI components for brand consistency
 */
function NetworkReport({ data, showPrintStyles = false, className }: NetworkReportProps) {
  return (
    <article
      className={cn(
        'space-y-8',
        showPrintStyles && 'print:bg-white print:text-black',
        className
      )}
    >
      {/* Page 1: Header + Executive Summary */}
      <ReportHeader
        retailerName={data.retailer_name}
        promoName={data.promo_name}
        promoPeriod={data.promo_period}
        generatedAt={data.generated_at}
      />

      <ExecutiveSummary data={data} />

      {/* Page 2: Network Effects Detail */}
      <NetworkEffectsDetail data={data} />

      {/* Page 3: Methodology */}
      <MethodologySection data={data} />

      {/* Print Footer */}
      <footer className="hidden print:block pt-8 border-t border-border text-center text-xs text-muted-foreground">
        <p>Generated by Cruxible • {new Date(data.generated_at).toLocaleDateString()}</p>
        <p className="mt-1">
          This report is for informational purposes only. Verify results with domain expertise.
        </p>
      </footer>
    </article>
  );
}

export { NetworkReport };
export type { NetworkReportProps };

// Re-export sub-components for flexibility
export { ReportHeader } from './report-header';
export { ExecutiveSummary } from './executive-summary';
export { NetworkEffectsDetail } from './network-effects-detail';
export { MethodologySection } from './methodology-section';
