// Generate src/api/generated/schema.ts from the pinned api/openapi.json.
//
// Two settings matter. `defaultNonNullable: false`: the daemon omits most
// defaulted fields from responses (pydantic exclude_if), so a field with a
// default is optional on the wire and must be optional in the types. And a
// post-pass for self-referencing value unions (ShownValue, QueryCell): as an
// interface member, `X: ... | components["schemas"]["X"][]` is a circular
// annotation (TS2502), so each becomes a top-level recursive type alias that
// the member points at. The output stays fully generated; never hand-edit it.
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const input = new URL("../api/openapi.json", import.meta.url);
const output = new URL("../src/api/generated/schema.ts", import.meta.url);

const ast = await openapiTS(JSON.parse(readFileSync(input, "utf8")), {
  defaultNonNullable: false,
});
let source = astToString(ast);

const recursive = [];
const lines = source.split("\n");
const out = [];
for (let i = 0; i < lines.length; i += 1) {
  const match = /^( {8})(\w+): (.*)$/.exec(lines[i]);
  if (!match) {
    out.push(lines[i]);
    continue;
  }
  const [, indent, name] = match;
  // A member spans lines until its own indent closes it with `;`.
  let end = i;
  while (end < lines.length - 1 && !(end === i ? lines[end].endsWith(";") : lines[end].startsWith(`${indent}}`) && lines[end].endsWith(";"))) {
    end += 1;
  }
  const member = lines.slice(i, end + 1).join("\n");
  const self = `components["schemas"]["${name}"]`;
  const rhs = member.slice(`${indent}${name}: `.length, -1);
  // Object members may reference themselves; only a bare union cannot.
  if (!member.includes(self) || rhs.startsWith("{")) {
    out.push(...lines.slice(i, end + 1));
  } else {
    const alias = `Recursive${name}`;
    recursive.push(`export type ${alias} = ${rhs.replaceAll(self, alias)};`);
    out.push(`${indent}${name}: ${alias};`);
  }
  i = end;
}
source = out.join("\n");

const header =
  "/**\n * This file was auto-generated by scripts/gen-api.mjs from api/openapi.json.\n" +
  " * Do not make direct changes to the file.\n */\n\n";
writeFileSync(output, header + source + (recursive.length ? `\n${recursive.join("\n")}\n` : ""));
console.log(
  `api/openapi.json -> src/api/generated/schema.ts` +
    (recursive.length ? ` (recursive aliases: ${recursive.length})` : ""),
);
